const dictionaries: Record<SupportedLocale, Record<TranslationKey, string>> = {
  "zh-CN": zh,
  "en-US": en,
};

type InterpolationValues = Record<string, string | number>;

type I18nContextValue = {
  locale: SupportedLocale;
  localePreference: LocalePreference;
  setLocalePreference: (preference: LocalePreference) => void;
  t: (key: TranslationKey, values?: InterpolationValues) => string;
  formatDate: (value: string | null) => string | null;
};

const I18nContext = createContext<I18nContextValue | null>(null);

function isSupportedPreference(value: string | null): value is LocalePreference {
  return value === "auto" || value === "zh-CN" || value === "en-US";
}

function readStoredPreference(): LocalePreference {
  try {
    const value = window.localStorage.getItem(STORAGE_KEY);
    return isSupportedPreference(value) ? value : "auto";
  } catch {
    return "auto";
  }
}

function detectSystemLocale(): SupportedLocale {
  if (typeof navigator === "undefined") {
    return "en-US";
  }

  const languages = navigator.languages?.length ? navigator.languages : [navigator.language];
  return languages.some((language) => language.toLowerCase().startsWith("zh"))
    ? "zh-CN"
    : "en-US";
}

function resolveLocale(preference: LocalePreference): SupportedLocale {
  return preference === "auto" ? detectSystemLocale() : preference;
}

function interpolate(template: string, values?: InterpolationValues) {
  if (!values) {
    return template;
  }

  return template.replace(/\{\{(\w+)\}\}/g, (match, key: string) => {
    const value = values[key];
    return value === undefined ? match : String(value);
  });
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [localePreference, setLocalePreferenceState] = useState<LocalePreference>(readStoredPreference);
  const [systemLocaleRevision, setSystemLocaleRevision] = useState(0);

  useEffect(() => {
    const handleLanguageChange = () => setSystemLocaleRevision((revision) => revision + 1);
    window.addEventListener("languagechange", handleLanguageChange);
    return () => window.removeEventListener("languagechange", handleLanguageChange);
  }, []);

  const locale = useMemo(
    () => resolveLocale(localePreference),
    [localePreference, systemLocaleRevision],
  );

  const setLocalePreference = useCallback((preference: LocalePreference) => {
    setLocalePreferenceState(preference);
    try {
      window.localStorage.setItem(STORAGE_KEY, preference);
    } catch {
      // Language choice is a preference; storage failures should not block app use.
    }
  }, []);

  const t = useCallback(
    (key: TranslationKey, values?: InterpolationValues) => {
      const template = dictionaries[locale][key] ?? dictionaries["en-US"][key] ?? key;
      return interpolate(template, values);
    },
    [locale],
  );

  const formatDate = useCallback(
    (value: string | null) => {
      if (!value) {
        return null;
      }
      const date = new Date(value);
      if (Number.isNaN(date.getTime())) {
        return null;
      }
      return date.toLocaleDateString(locale, {
        year: "numeric",
        month: "short",
        day: "numeric",
      });
    },
    [locale],
  );

  const value = useMemo<I18nContextValue>(
    () => ({ locale, localePreference, setLocalePreference, t, formatDate }),
    [formatDate, locale, localePreference, setLocalePreference, t],
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const context = useContext(I18nContext);
  if (!context) {
    throw new Error("useI18n must be used within I18nProvider");
  }
  return context;
}
